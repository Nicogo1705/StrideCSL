using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Csl.Generators.CSharp;

/// <summary>
/// The generated half of every [Shader] class: <c>streams</c>, typed as the class, so shader code reads
/// <c>streams.Position</c> as SDSL does; and, since C# has one base class where SDSL has many, the
/// members of the [Mixin] shaders declared again as stubs, so the C# compiles and the translator
/// resolves them as shader members. A stub is not virtual: to override a method of a mixin, mark the
/// method [Override].
/// </summary>
public static class ShaderPartialEmitter
{
    private static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier | SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    public static string Emit(INamedTypeSymbol shader, TranslatedShader result)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// Generated by Csl.Generators: streams, and the members of the [Mixin] shaders as stubs for the C# compiler.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS0108, CS0109, CS0114, CS0649, CS8618, CS1591");
        if (result.Namespace != null)
        {
            sb.Append("namespace ").AppendLine(result.Namespace);
            sb.AppendLine("{");
        }
        var indent = result.Namespace != null ? "    " : string.Empty;
        sb.Append(indent).Append("partial class ").AppendLine(result.ClassName);
        sb.Append(indent).AppendLine("{");

        var self = shader.ToDisplayString(TypeFormat);
        bool baseIsShader = shader.BaseType != null && ShaderTranslator.IsShaderClass(shader.BaseType);
        sb.Append(indent).AppendLine("    /// <summary>The streams of the shader, as in SDSL: <c>streams.Position</c>.</summary>");
        sb.Append(indent).AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
        sb.Append(indent).Append("    protected ").Append(baseIsShader ? "new " : string.Empty).Append(self).AppendLine(" streams { get => this; set { } }");
        sb.Append(indent).AppendLine("    /// <summary>A member named by a MemberName generic parameter: <c>streams[TName]</c> is SDSL's <c>streams.TName</c>.</summary>");
        sb.Append(indent).AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
        sb.Append(indent).Append("    public ").Append(baseIsShader ? "new " : string.Empty).AppendLine("dynamic this[global::Csl.MemberName name] { get => global::Csl.Cpu.Members.Get(this, name.Name!); set => global::Csl.Cpu.Members.Set(this, name.Name!, value); }");
        sb.Append(indent).AppendLine("    /// <summary>A stream the shader does not declare, that the effect mixes in: <c>streams[\"PositionWS\"]</c>.</summary>");
        sb.Append(indent).AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
        sb.Append(indent).Append("    public ").Append(baseIsShader ? "new " : string.Empty).AppendLine("dynamic this[string name] { get => global::Csl.Cpu.Members.Get(this, name); set => global::Csl.Cpu.Members.Set(this, name, value); }");

        // Names the class already has: its own, its C# bases', and what the stubs of its C# bases bring.
        var taken = new HashSet<string>(System.StringComparer.Ordinal) { "streams" };
        var covered = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        for (var type = shader; type != null && type.SpecialType != SpecialType.System_Object; type = type.BaseType)
        {
            covered.Add(type);
            foreach (var member in type.GetMembers())
                taken.Add(member.Name);
        }
        for (var type = shader.BaseType; type != null && type.SpecialType != SpecialType.System_Object; type = type.BaseType)
        {
            // A base in this compilation gets its stubs generated too; they are not in its members yet.
            if (type.Locations.Any(l => l.IsInSource))
                foreach (var mixin in MixinsOf(type))
                    foreach (var member in AllMembers(mixin, covered))
                        taken.Add(member.Name);
        }

        // Methods by signature: a mixin may overload a name another mixin has.
        var methods = new HashSet<string>(System.StringComparer.Ordinal);
        for (var type = shader; type != null && type.SpecialType != SpecialType.System_Object; type = type.BaseType)
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>())
                methods.Add(Signature(method));
        foreach (var mixin in MixinsOf(shader))
        {
            foreach (var member in AllMembers(mixin, covered))
            {
                if (member.IsImplicitlyDeclared || member.DeclaredAccessibility == Accessibility.Private)
                    continue;
                if (member is IMethodSymbol { MethodKind: MethodKind.Ordinary } overload)
                {
                    if (!methods.Add(Signature(overload)) || (taken.Contains(member.Name) && !methods.Any(m => m.StartsWith(member.Name + "(", System.StringComparison.Ordinal))))
                        continue;
                    taken.Add(member.Name);
                }
                else if (!taken.Add(member.Name))
                    continue;
                switch (member)
                {
                    case IFieldSymbol field when !field.IsConst:
                        foreach (var attribute in field.GetAttributes())
                        {
                            var name = attribute.AttributeClass?.ToDisplayString();
                            if (name == "Csl.StreamAttribute")
                            {
                                var semantic = attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is string s ? "(\"" + s + "\")" : string.Empty;
                                sb.Append(indent).Append("    [global::Csl.Stream").Append(semantic).AppendLine("]");
                            }
                            else if (name == "Csl.StageAttribute")
                                sb.Append(indent).AppendLine("    [global::Csl.Stage]");
                            else if (name == "Csl.ComposeAttribute")
                                sb.Append(indent).AppendLine("    [global::Csl.Compose]");
                            else if (name == "Csl.GenericAttribute")
                                sb.Append(indent).AppendLine("    [global::Csl.Generic]");
                        }
                        sb.Append(indent).Append("    public ").Append(field.IsStatic ? "static " : string.Empty)
                          .Append(field.Type.ToDisplayString(TypeFormat)).Append(' ').Append(Escape(field.Name)).AppendLine(";");
                        break;
                    case IFieldSymbol constant:
                        sb.Append(indent).Append("    public const ").Append(constant.Type.ToDisplayString(TypeFormat)).Append(' ').Append(Escape(constant.Name))
                          .Append(" = ").Append(Literal(constant.ConstantValue)).AppendLine(";");
                        break;
                    case IMethodSymbol { MethodKind: MethodKind.Ordinary } method:
                        // A stub: the debugger steps through it, into the mixin's method.
                        sb.Append(indent).AppendLine("    [global::System.Diagnostics.DebuggerNonUserCode]");
                        sb.Append(indent).Append("    public ").Append(method.IsStatic ? "static " : string.Empty)
                          .Append(method.ReturnType.ToDisplayString(TypeFormat)).Append(' ').Append(Escape(method.Name)).Append('(');
                        for (int i = 0; i < method.Parameters.Length; i++)
                        {
                            var parameter = method.Parameters[i];
                            if (i > 0) sb.Append(", ");
                            sb.Append(parameter.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", RefKind.In => "in ", _ => string.Empty });
                            sb.Append(parameter.Type.ToDisplayString(TypeFormat)).Append(' ').Append(Escape(parameter.Name));
                        }
                        sb.Append(')');
                        // On the CPU the call runs the mixin's own method (Csl.Cpu.Mixins): on a static one
                        // directly, on an instance one through the mixin's instance kept for this shader.
                        var owner = method.ContainingType;
                        var arguments = string.Join(", ", method.Parameters.Select(p => (p.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", _ => string.Empty }) + Escape(p.Name)));
                        var ownerName = owner.ToDisplayString(TypeFormat);
                        if (owner.IsGenericType)
                            sb.AppendLine(" => throw global::Csl.Gpu.Only;");
                        else if (method.IsStatic)
                            sb.Append(" => ").Append(ownerName).Append('.').Append(Escape(method.Name)).Append('(').Append(arguments).AppendLine(");");
                        else
                            sb.Append(" { var mixin = global::Csl.Cpu.Mixins.Enter<").Append(ownerName).Append(">(this); try { ")
                              .Append(method.ReturnsVoid ? string.Empty : "return ").Append("mixin.").Append(Escape(method.Name)).Append('(').Append(arguments)
                              .AppendLine("); } finally { global::Csl.Cpu.Mixins.Leave(this, mixin); } }");
                        break;
                }
            }
        }

        sb.Append(indent).AppendLine("}");
        if (result.Namespace != null)
            sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>The [Mixin] shaders of a class, in order.</summary>
    public static List<INamedTypeSymbol> MixinsOf(INamedTypeSymbol type)
    {
        var result = new List<INamedTypeSymbol>();
        foreach (var attribute in type.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() != "Csl.MixinAttribute")
                continue;
            foreach (var argument in attribute.ConstructorArguments.SelectMany(a => a.Kind == TypedConstantKind.Array ? a.Values : System.Collections.Immutable.ImmutableArray.Create(a)))
            {
                if (argument.Value is INamedTypeSymbol mixin)
                    result.Add(mixin);
            }
        }
        return result;
    }

    /// <summary>
    /// The members a mixin brings: its own, its C# bases', and its own mixins', recursively. Types
    /// already in <paramref name="covered"/> are skipped, and added as they are visited.
    /// </summary>
    public static IEnumerable<ISymbol> AllMembers(INamedTypeSymbol mixin, HashSet<INamedTypeSymbol> covered)
    {
        for (var type = mixin; type != null && type.SpecialType != SpecialType.System_Object; type = type.BaseType)
        {
            if (!covered.Add(type))
                continue;
            foreach (var member in type.GetMembers().OrderBy(m => m.Locations.FirstOrDefault()?.SourceSpan.Start ?? 0))
                yield return member;
            if (type.Locations.Any(l => l.IsInSource))
            {
                foreach (var inner in MixinsOf(type))
                    foreach (var member in AllMembers(inner, covered))
                        yield return member;
            }
        }
    }

    private static string Signature(IMethodSymbol method) =>
        method.Name + "(" + string.Join(",", method.Parameters.Select(p => p.RefKind + " " + p.Type.ToDisplayString())) + ")";

    private static string Escape(string name) => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;

    private static string Literal(object? value) => value switch
    {
        null => "default",
        bool b => b ? "true" : "false",
        float f => float.IsPositiveInfinity(f) ? "float.PositiveInfinity" : float.IsNegativeInfinity(f) ? "float.NegativeInfinity" : float.IsNaN(f) ? "float.NaN" : f.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f",
        double d => d.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d",
        uint u => u.ToString(System.Globalization.CultureInfo.InvariantCulture) + "u",
        string s => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"",
        _ => System.Convert.ToString(value, System.Globalization.CultureInfo.InvariantCulture) ?? "default",
    };
}
